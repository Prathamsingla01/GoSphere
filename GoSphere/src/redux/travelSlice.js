import { createSlice } from '@reduxjs/toolkit';

// Initial state for Redux Toolkit travel slice
const initialState = {
  savedTrips: [],
};

// Create a Redux slice for managing shortlisted / saved journeys
export const travelSlice = createSlice({
  name: 'travel',
  initialState,
  reducers: {
    // Reducer to add a travel option to saved journeys
    saveTrip: (state, action) => {
      const exists = state.savedTrips.some((trip) => trip.id === action.payload.id);
      if (!exists) {
        state.savedTrips.push(action.payload);
      }
    },
    // Reducer to remove a journey from saved list by its id
    removeTrip: (state, action) => {
      state.savedTrips = state.savedTrips.filter((trip) => trip.id !== action.payload);
    },
    // Reducer to clear all saved journeys
    clearSavedTrips: (state) => {
      state.savedTrips = [];
    },
  },
});

// Export action creators generated by createSlice
export const { saveTrip, removeTrip, clearSavedTrips } = travelSlice.actions;

// Export reducer for store configuration
export default travelSlice.reducer;
